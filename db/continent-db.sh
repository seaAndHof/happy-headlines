#!/bin/sh
# A continent's ArticleDatabase (z-axis split): the same table as the global database, seeded with a few articles
# named after its continent, so it's easy to see which database answered. CONTINENT is set in compose.yaml.
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v continent="$CONTINENT" <<'SQL'
CREATE TABLE articles (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        text NOT NULL,
    content      text NOT NULL,
    published_at timestamptz NOT NULL
);

INSERT INTO articles (title, content, published_at)
SELECT 'Good news from ' || :'continent' || ' #' || n,
       'A positive story from ' || :'continent' || '.',
       now() - n * interval '1 day'
FROM generate_series(1, 5) AS n;
SQL
